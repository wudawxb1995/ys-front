const g = (id, name, icon, children) => ({ id, name, icon, children })
const leaf = (id, name, page) => ({ id, name, page })
const work = (scene, focus) => ({ type: 'agent-work', scene, focus })

function fns(prefix, scene, items) {
  return items.map(([id, name]) => leaf(`${prefix}-${id}`, name, work(scene, id)))
}

