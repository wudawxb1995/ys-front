function b(label, text) {
  return `<p><b>【${label}】</b>${text}</p>`
}

function h(id, title) {
  return `<h5 id="doc-${id}">${title}</h5>`
}

function src(page, path) {
  return `某型装备研制总要求第${page}页 / 指标树 V1.0 · ${path}`
}

function std(id, title, purpose, criteria, source, cond, steps, record, abnormal) {
  return h(id, title)
    + b('考核目的', purpose)
    + b('判定依据', `${criteria}；判据来源为${source}。`)
    + b('试验条件与资源', cond)
    + b('实施步骤', steps)
    + b('数据记录与处理', record)
    + b('异常处置', abnormal)
}

