const algoBias = { vector: 0, llm: -1, graph: -3, seq: -5, modal: -2, hybrid: 1 }

export function recommendForIndicator(ind, algoKey = 'vector') {
  if (!ind) return { basis: '', items: [] }
  const pack = ind.id === 'i01' ? i01 : byKlass(ind)
  const bias = algoBias[algoKey] ?? 0
  return {
    basis: pack.basis,
    items: pack.items.map((row) => ({
      ...row,
      score: Math.max(61, Math.min(99, row.score + bias)),
    })),
  }
}
