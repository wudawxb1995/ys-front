const pad = n => String(n).padStart(3, '0')

export const resourceCorpus = (() => {
  const rows = showcase.map((row, index) => [...row, owners[index % owners.length], `2026-10-${String(8 + index % 15).padStart(2, '0')} 09:24`])
  for (const { name: category, count } of resourceCategoryTargets) {
    const existing = rows.filter(row => row[1] === category).length
    for (let i = 0; i < count - existing; i++) {
      const topic = topics[category][i % topics[category].length]
      const type = types[Math.floor(i / topics[category].length) % types.length]
      const year = 2018 + i % 8
      const format = i % 9 === 0 ? 'DOCX' : i % 11 === 0 ? 'XLSX' : 'PDF'
      const modal = format === 'XLSX' ? '表格' : '文本'
      const pages = format === 'XLSX' ? '—' : String(24 + i % 116)
      rows.push([`${year}年${topic}${type}（档案${pad(i + 1)}）`, category, format, modal, `${(2.4 + i % 23 * 0.7).toFixed(1)} MB`, pages, '已解析', owners[i % owners.length], `${year}-11-${String(1 + i % 27).padStart(2, '0')} 10:30`])
    }
  }
  return rows
})()
