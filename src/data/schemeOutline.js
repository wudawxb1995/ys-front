function buildIndicatorChapters(indicators) {
  return CHAPTERS.map((chapter) => {
    const rows = indicators.filter((item) => String(item.klass || '').startsWith(chapter.key))
    const body = rows.map((item, index) => (
      item.name === '立靶高低中间偏差'
        ? fireSpecial(item)
        : genericIndicator(item, index, chapter.num)
    )).join('')
    return {
      no: chapter.no,
      title: `${chapter.title}（${rows.length}项）`,
      content: body || '<p>本章暂无纳入指标。</p>',
    }
  })
}

