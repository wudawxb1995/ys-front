function tag(label, text) {
  return `<p><b>【${label}】</b>${text}</p>`
}

function factorText(factors) {
  if (!factors?.length) {
    return '目标类型（固定靶/运动靶）；目标距离（1000 m/1500 m/2000 m）；弹种（杀伤爆破弹/破甲弹）；装药号（全装药/二号装药）；瞄准方式（直接瞄准/间接瞄准）；射击方式（单发/连发）；海拔高度（平原/高原）；能见度（良好/一般）；温度（常温/高温/低温）；风速（静风/3～5级/5级以上）；气压（标准/低压）；操作人员（基准班组/加强班组）；弹药批次（批次A/批次B）；身管状态（新身管/寿命中期）；供电方式（车载电源/外接电源）；通信工况（开机/关机）；振动工况（静止/行驶后）；贮存经历（库存贮存/野战贮存）'
  }
  return factors.map((item) => `${item.name}（${item.levels}）`).join('；')
}

